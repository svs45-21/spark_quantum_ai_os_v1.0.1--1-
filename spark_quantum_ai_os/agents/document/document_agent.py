# ── DOCX ──────────────────────────────────────────────────────────────────────

class DocxWriter:
    def create(self, title: str, sections: List[Dict], author: str = "SPARK AI") -> str:
        try:
            from docx import Document
            from docx.shared import Pt, RGBColor, Inches
            from docx.enum.text import WD_ALIGN_PARAGRAPH

            doc = Document()

            # Title
            t = doc.add_heading(title, level=0)
            t.alignment = WD_ALIGN_PARAGRAPH.CENTER

            # Metadata
            meta = doc.add_paragraph()
            meta.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = meta.add_run(f"Generated by SPARK QUANTUM AI OS | {author} | {datetime.now().strftime('%B %d, %Y')}")
            run.font.size = Pt(10)
            run.font.color.rgb = RGBColor(0x80, 0x80, 0x80)

            doc.add_paragraph()

            for section in sections:
                heading = section.get("heading", "")
                body = section.get("body", "")
                level = section.get("level", 1)

                if heading:
                    doc.add_heading(heading, level=level)

                if body:
                    for paragraph in body.split("\n\n"):
                        p = paragraph.strip()
                        if p:
                            doc.add_paragraph(p)

                # Table support
                if "table" in section:
                    table_data = section["table"]
                    headers = table_data.get("headers", [])
                    rows = table_data.get("rows", [])
                    if headers:
                        table = doc.add_table(rows=1 + len(rows), cols=len(headers))
                        table.style = "Table Grid"
                        hdr = table.rows[0].cells
                        for i, h in enumerate(headers):
                            hdr[i].text = h
                        for r_idx, row in enumerate(rows):
                            cells = table.rows[r_idx + 1].cells
                            for c_idx, val in enumerate(row):
                                cells[c_idx].text = str(val)
                        doc.add_paragraph()

            filename = f"{title.replace(' ', '_')[:40]}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.docx"
            path = OUTPUT_DIR / filename
            doc.save(str(path))
            return str(path)
        except ImportError:
            raise RuntimeError("python-docx not installed. Run: pip install python-docx")


# ── PDF ───────────────────────────────────────────────────────────────────────

class PDFWriter:
    def create(self, title: str, sections: List[Dict], author: str = "SPARK AI") -> str:
        try:
            from fpdf import FPDF

            pdf = FPDF()
            pdf.set_auto_page_break(auto=True, margin=15)
            pdf.add_page()

            # Title
            pdf.set_font("Helvetica", "B", 20)
            pdf.set_text_color(0, 80, 160)
            pdf.multi_cell(0, 12, title, align="C")
            pdf.ln(4)

            # Metadata
            pdf.set_font("Helvetica", "", 9)
            pdf.set_text_color(120, 120, 120)
            pdf.cell(0, 6, f"SPARK QUANTUM AI OS  |  {author}  |  {datetime.now().strftime('%B %d, %Y')}", align="C")
            pdf.ln(10)

            pdf.set_text_color(0, 0, 0)

            for section in sections:
                heading = section.get("heading", "")
                body = section.get("body", "")
                level = section.get("level", 1)

                if heading:
                    size = 14 if level == 1 else 12 if level == 2 else 11
                    pdf.set_font("Helvetica", "B", size)
                    pdf.set_text_color(0, 60, 120)
                    pdf.multi_cell(0, 8, heading)
                    pdf.set_text_color(0, 0, 0)
                    pdf.ln(2)

                if body:
                    pdf.set_font("Helvetica", "", 11)
                    for para in body.split("\n\n"):
                        p = para.strip()
                        if p:
                            pdf.multi_cell(0, 6, p)
                            pdf.ln(3)

            filename = f"{title.replace(' ', '_')[:40]}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
            path = OUTPUT_DIR / filename
            pdf.output(str(path))
            return str(path)
        except ImportError:
            raise RuntimeError("fpdf2 not installed. Run: pip install fpdf2")


# ── PPTX ──────────────────────────────────────────────────────────────────────

class PPTXWriter:
    def create(self, title: str, slides: List[Dict], author: str = "SPARK AI") -> str:
        try:
            from pptx import Presentation
            from pptx.util import Inches, Pt, Emu
            from pptx.dml.color import RGBColor as PptxRGB
            from pptx.enum.text import PP_ALIGN

            prs = Presentation()
            prs.slide_width = Inches(13.33)
            prs.slide_height = Inches(7.5)

            # Title slide
            title_layout = prs.slide_layouts[0]
            slide = prs.slides.add_slide(title_layout)
            slide.shapes.title.text = title
            slide.placeholders[1].text = f"{author}  |  {datetime.now().strftime('%B %Y')}"

            for slide_data in slides:
                layout = prs.slide_layouts[1]  # Title + Content
                sl = prs.slides.add_slide(layout)

                slide_title = slide_data.get("title", "")
                content = slide_data.get("content", "")
                bullets = slide_data.get("bullets", [])

                sl.shapes.title.text = slide_title

                tf = sl.placeholders[1].text_frame
                tf.clear()

                if content:
                    p = tf.paragraphs[0]
                    p.text = content
                    p.font.size = Pt(18)

                for bullet in bullets:
                    p = tf.add_paragraph()
                    p.text = str(bullet)
                    p.level = 1
                    p.font.size = Pt(16)

            filename = f"{title.replace(' ', '_')[:40]}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pptx"
            path = OUTPUT_DIR / filename
            prs.save(str(path))
            return str(path)
        except ImportError:
            raise RuntimeError("python-pptx not installed. Run: pip install python-pptx")


# ── Excel ─────────────────────────────────────────────────────────────────────

class ExcelWriter:
    def create(self, title: str, sheets: List[Dict]) -> str:
        try:
            import openpyxl
            from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
            from openpyxl.utils import get_column_letter

            wb = openpyxl.Workbook()
            wb.remove(wb.active)  # Remove default sheet

            header_fill = PatternFill(start_color="003366", end_color="003366", fill_type="solid")
            header_font = Font(color="FFFFFF", bold=True, size=11)
            thin = Side(style="thin")
            border = Border(left=thin, right=thin, top=thin, bottom=thin)

            for sheet_data in sheets:
                sheet_name = sheet_data.get("name", "Sheet")[:31]
                headers = sheet_data.get("headers", [])
                rows = sheet_data.get("rows", [])

                ws = wb.create_sheet(title=sheet_name)

                # Title row
                ws.merge_cells(f"A1:{get_column_letter(max(len(headers), 1))}1")
                ws["A1"] = title
                ws["A1"].font = Font(bold=True, size=14)
                ws["A1"].alignment = Alignment(horizontal="center")

                # Headers
                for col, header in enumerate(headers, 1):
                    cell = ws.cell(row=2, column=col, value=header)
                    cell.font = header_font
                    cell.fill = header_fill
                    cell.alignment = Alignment(horizontal="center")
                    cell.border = border

                # Data rows
                for r_idx, row in enumerate(rows, 3):
                    for c_idx, val in enumerate(row, 1):
                        cell = ws.cell(row=r_idx, column=c_idx, value=val)
                        cell.border = border
                        if r_idx % 2 == 0:
                            cell.fill = PatternFill(start_color="EBF3FF", end_color="EBF3FF", fill_type="solid")

                # Auto-width
                for col in ws.columns:
                    max_len = max((len(str(c.value or "")) for c in col), default=10)
                    ws.column_dimensions[get_column_letter(col[0].column)].width = min(max_len + 4, 60)

            filename = f"{title.replace(' ', '_')[:40]}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.xlsx"
            path = OUTPUT_DIR / filename
            wb.save(str(path))
            return str(path)
        except ImportError:
            raise RuntimeError("openpyxl not installed. Run: pip install openpyxl")


# ── Markdown ──────────────────────────────────────────────────────────────────

class MarkdownWriter:
    def create(self, title: str, sections: List[Dict]) -> str:
        lines = [f"# {title}", "", f"*Generated by SPARK QUANTUM AI OS — {datetime.now().strftime('%B %d, %Y')}*", ""]
        for section in sections:
            heading = section.get("heading", "")
            body = section.get("body", "")
            level = section.get("level", 1)
            if heading:
                lines.append(f"{'#' * (level + 1)} {heading}")
                lines.append("")
            if body:
                lines.append(body)
                lines.append("")
        content = "\n".join(lines)
        filename = f"{title.replace(' ', '_')[:40]}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.md"
        path = OUTPUT_DIR / filename
        path.write_text(content, encoding="utf-8")
        return str(path)


# ── Document Agent ─────────────────────────────────────────────────────────────

class DocumentAgent(BaseAgent):
    name = "document_agent"
    description = "Creates professional documents: DOCX, PDF, PPTX, Excel, Markdown."
    capabilities = [
        AgentCapability("create_report", "Generate a full research report"),
        AgentCapability("create_literature_review", "Generate a literature review"),
        AgentCapability("create_presentation", "Generate a PPTX presentation"),
        AgentCapability("create_spreadsheet", "Generate an Excel spreadsheet"),
        AgentCapability("create_markdown", "Generate a Markdown document"),
        AgentCapability("create_proposal", "Generate a project proposal"),
    ]

    def __init__(
        self,
        router: Optional[ModelRouter] = None,
        bus: Optional[EventBus] = None,
        settings=None,
    ) -> None:
        super().__init__(bus)
        from core.settings import get_settings
        cfg = settings or get_settings()
        self._router = router or ModelRouter()
        self._user_name = cfg.spark.user.name
        self._docx = DocxWriter()
        self._pdf = PDFWriter()
        self._pptx = PPTXWriter()
        self._excel = ExcelWriter()
        self._md = MarkdownWriter()

    async def execute(self, task: Task) -> Any:
        action = task.payload.get("action", "")
        params = task.payload.get("params", {})

        if action == "create_report":
            return await self._create_report(params)
        elif action == "create_literature_review":
            return await self._create_literature_review(params)
        elif action == "create_presentation":
            return await self._create_presentation(params)
        elif action == "create_spreadsheet":
            return await self._create_spreadsheet(params)
        elif action == "create_markdown":
            return await self._create_markdown(params)
        elif action == "create_proposal":
            return await self._create_proposal(params)
        else:
            raise ValueError(f"Unknown document action: {action}")

    async def _generate_content(self, prompt: str, max_tokens: int = 4000) -> str:
        return await self._router.complete(
            messages=[{"role": "user", "content": prompt}],
            task_type=TaskType.RESEARCH,
            max_tokens=max_tokens,
            temperature=0.4,
            system=(
                "You are an expert academic and technical writer. "
                "Generate detailed, well-structured, professional content. "
                "Use clear headings and thorough explanations."
            ),
        )

    async def _create_report(self, params: Dict) -> Dict:
        topic = params.get("topic", "")
        fmt = params.get("format", "docx").lower()

        prompt = f"""Write a comprehensive technical report on: {topic}

Structure:
1. Executive Summary
2. Introduction
3. Background and Context
4. Main Analysis (3-5 sections)
5. Key Findings
6. Recommendations
7. Conclusion
8. References

Write each section fully. Use professional academic language."""

        raw = await self._generate_content(prompt)
        sections = self._parse_sections(raw)
        title = f"Report: {topic}"

        paths = {}
        loop = asyncio.get_event_loop()

        if fmt in ("docx", "all"):
            paths["docx"] = await loop.run_in_executor(None, self._docx.create, title, sections, self._user_name)
        if fmt in ("pdf", "all"):
            paths["pdf"] = await loop.run_in_executor(None, self._pdf.create, title, sections, self._user_name)
        if fmt in ("md", "markdown", "all"):
            paths["md"] = await loop.run_in_executor(None, self._md.create, title, sections)

        await self._bus.emit(
            EventType.DOCUMENT_CREATED,
            {"title": title, "format": fmt, "paths": paths},
            source=self.name,
        )

        return {"title": title, "paths": paths, "sections": len(sections)}

    async def _create_literature_review(self, params: Dict) -> Dict:
        topic = params.get("topic", "")
        fmt = params.get("format", "docx").lower()

        prompt = f"""Write a comprehensive literature review on: {topic}

Structure:
1. Abstract (250 words)
2. Introduction
3. Theoretical Framework
4. Review of Literature (organized by theme or chronology)
   - Theme/Period 1
   - Theme/Period 2
   - Theme/Period 3
5. Critical Analysis and Synthesis
6. Research Gaps
7. Conclusion
8. References (APA format, at least 15 realistic citations)

Be thorough and academic. Cite key researchers and seminal works."""

        raw = await self._generate_content(prompt, max_tokens=6000)
        sections = self._parse_sections(raw)
        title = f"Literature Review: {topic}"

        paths = {}
        loop = asyncio.get_event_loop()

        if fmt in ("docx", "all"):
            paths["docx"] = await loop.run_in_executor(None, self._docx.create, title, sections, self._user_name)
        if fmt in ("pdf", "all"):
            paths["pdf"] = await loop.run_in_executor(None, self._pdf.create, title, sections, self._user_name)

        await self._bus.emit(EventType.DOCUMENT_CREATED, {"title": title, "paths": paths}, source=self.name)
        return {"title": title, "paths": paths, "sections": len(sections)}

    async def _create_presentation(self, params: Dict) -> Dict:
        topic = params.get("topic", "")
        num_slides = params.get("slides", 10)

        prompt = f"""Create a {num_slides}-slide presentation on: {topic}

For each slide provide:
SLIDE_TITLE: <title>
SLIDE_CONTENT: <1-2 sentence summary>
BULLETS:
- bullet 1
- bullet 2
- bullet 3

Include: title slide, agenda, main content slides, conclusion, Q&A slide."""

        raw = await self._generate_content(prompt, max_tokens=3000)
        slides = self._parse_slides(raw)
        title = f"{topic}"

        loop = asyncio.get_event_loop()
        path = await loop.run_in_executor(None, self._pptx.create, title, slides, self._user_name)

        await self._bus.emit(EventType.DOCUMENT_CREATED, {"title": title, "path": path}, source=self.name)
        return {"title": title, "path": path, "slides": len(slides)}

    async def _create_spreadsheet(self, params: Dict) -> Dict:
        topic = params.get("topic", "")
        headers = params.get("headers", [])
        rows = params.get("rows", [])
        sheets = params.get("sheets", [{"name": "Data", "headers": headers, "rows": rows}])

        if not sheets[0]["headers"] and topic:
            prompt = f"""Generate realistic spreadsheet data for: {topic}
Return JSON: {{"headers": ["col1","col2",...], "rows": [["val1","val2",...], ...]}}
Include at least 10 rows. Return only JSON, no other text."""
            raw = await self._generate_content(prompt, max_tokens=2000)
            import json
            try:
                data = json.loads(raw.strip().strip("```json").strip("```"))
                sheets = [{"name": topic[:31], "headers": data["headers"], "rows": data["rows"]}]
            except Exception:
                pass

        title = params.get("title", topic or "SPARK Data")
        loop = asyncio.get_event_loop()
        path = await loop.run_in_executor(None, self._excel.create, title, sheets)

        await self._bus.emit(EventType.DOCUMENT_CREATED, {"title": title, "path": path}, source=self.name)
        return {"title": title, "path": path}

    async def _create_markdown(self, params: Dict) -> Dict:
        topic = params.get("topic", "")
        content = params.get("content", "")

        if not content and topic:
            content = await self._generate_content(f"Write detailed documentation on: {topic}")

        sections = self._parse_sections(content)
        title = params.get("title", topic)
        loop = asyncio.get_event_loop()
        path = await loop.run_in_executor(None, self._md.create, title, sections)

        return {"title": title, "path": path}

