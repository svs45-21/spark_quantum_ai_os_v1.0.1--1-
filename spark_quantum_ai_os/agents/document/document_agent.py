    def _parse_sections(self, raw: str) -> List[Dict]:
        """Convert raw LLM output into structured sections list."""
        import re
        sections = []
        current_heading = ""
        current_body = []
        current_level = 1

        for line in raw.split("\n"):
            h1 = re.match(r"^# (.+)", line)
            h2 = re.match(r"^## (.+)", line)
            h3 = re.match(r"^### (.+)", line)
            numbered = re.match(r"^\d+\.\s+\*?\*?(.+?)\*?\*?$", line)

            if h1:
                if current_body:
                    sections.append({"heading": current_heading, "body": "\n\n".join(current_body), "level": current_level})
                current_heading = h1.group(1)
                current_body = []
                current_level = 1
            elif h2:
                if current_body:
                    sections.append({"heading": current_heading, "body": "\n\n".join(current_body), "level": current_level})
                current_heading = h2.group(1)
                current_body = []
                current_level = 2
            elif h3:
                if current_body:
                    sections.append({"heading": current_heading, "body": "\n\n".join(current_body), "level": current_level})
                current_heading = h3.group(1)
                current_body = []
                current_level = 3
            elif numbered and len(line.strip()) < 60:
                if current_body:
                    sections.append({"heading": current_heading, "body": "\n\n".join(current_body), "level": current_level})
                current_heading = numbered.group(1)
                current_body = []
                current_level = 1
            else:
                if line.strip():
                    current_body.append(line.strip())

        if current_body or current_heading:
            sections.append({"heading": current_heading, "body": "\n\n".join(current_body), "level": current_level})

        if not sections:
            sections = [{"heading": "", "body": raw, "level": 1}]

        return sections

    def _parse_slides(self, raw: str) -> List[Dict]:
        """Parse slide data from LLM output."""
        slides = []
        current = {}
        in_bullets = False
        bullets = []

        for line in raw.split("\n"):
            line = line.strip()
            if line.startswith("SLIDE_TITLE:"):
                if current:
                    current["bullets"] = bullets
                    slides.append(current)
                current = {"title": line.replace("SLIDE_TITLE:", "").strip()}
                bullets = []
                in_bullets = False
            elif line.startswith("SLIDE_CONTENT:"):
                current["content"] = line.replace("SLIDE_CONTENT:", "").strip()
            elif line == "BULLETS:":
                in_bullets = True
            elif in_bullets and line.startswith("-"):
                bullets.append(line.lstrip("- ").strip())

        if current:
            current["bullets"] = bullets
            slides.append(current)

        return slides
